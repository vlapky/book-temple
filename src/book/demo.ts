import { parseMarkdown } from './parse'
import type { Book } from './types'

const DEMO = `# Добро пожаловать

Это Храм Книги — спокойное место, чтобы читать или слушать. Здесь нет рекламы, счётчиков и спешки. Есть только текст, ваш темп и несколько инструментов, которые помогают не терять нить.

Откройте свою книгу кнопкой «Открыть» или просто перетащите файл в окно. Подходят форматы FB2, EPUB, TXT, Markdown и HTML. Книги хранятся только на этом устройстве и никуда не отправляются.

Если читать трудно — это не ваша вина. Длинные абзацы, мелкий шрифт и яркий фон утомляют почти всех. Попробуйте изменить оформление под себя: всё сохранится автоматически.

## Как настроить текст

Нажмите «Оформление» или клавишу S. Можно выбрать шрифт, размер, межстрочный интервал, расстояние между буквами и словами, ширину колонки. Шрифт Andika создан специально для тех, кому сложно различать похожие буквы.

Цветовых тем пять: дневная, ночная, сепия, кремовая и цифровая — зелёные буквы на глубоком чёрном фоне. Контраст и цвет фона можно подстроить тонко, а рядом с ползунком видно, насколько текст читаем по стандарту WCAG.

# Чтение вслух

Нажмите пробел, и текст зазвучит. Текущее слово и предложение подсвечиваются, а страница прокручивается сама. Стрелки влево и вправо переносят на предложение назад или вперёд, клавиши плюс и минус меняют скорость.

Нейросетевые голоса работают прямо в браузере: модель скачивается один раз, около 285 мегабайт, и дальше озвучка работает без интернета. Голосов 57, мужских и женских. Пока модель не загружена, можно слушать системный голос устройства.

Скорость воспроизведения меняется от 0,5 до 4 раз, причём высота голоса не плывёт. Отдельно настраивается темп самой речи: он влияет на то, как диктор произносит слова, а не на скорость перемотки.

Числа читаются словами: в 1812 году, 3-й том, 25 человек. Если в тексте стоит знак ударения, например в слове за́мок, синтезатор его учтёт[^1].

[^1]: Знак ударения — это комбинируемый акут U+0301. Его ставят в учебных текстах и словарях.

# Когда трудно сосредоточиться

Режим фокусировки (клавиша F) убирает всё лишнее: меню, панели, уведомления. Остаётся только текст. Выйти — клавиша Escape.

Направляющая линейка (клавиша G) затемняет всё, кроме текущей строки или абзаца. Она следует за мышью, прокруткой или голосом, если включено чтение вслух.

Разбивка на блоки делит длинную главу на небольшие части. Можно показывать их по одному: так легче начать и проще вернуться после перерыва. Прогресс главы и книги всегда виден вверху.

Режим RSVP (клавиша R) показывает слова по одному в центре экрана. Глазам не нужно бегать по строке, а темп задаёте вы.

## Закладки и заметки

Клавиша B ставит закладку на текущем предложении. Выделите фрагмент мышью, и появится панель: можно отметить его цветом, написать заметку или начать чтение вслух с этого места. Клавиша H выделяет текущее предложение без мыши.

Все закладки и заметки собраны на одной панели. Заметки можно выгрузить в Markdown.

## Короткое стихотворение для проверки

Тихо падает свет на страницу,
строчка за строчкой ведёт,
можно не торопиться —
книга подождёт.

Приятного чтения!
`

export function demoBook(): Book {
  const book = parseMarkdown(DEMO, 'Храм Книги')
  // Стихотворение: каждая строка — отдельный стих.
  for (const ch of book.chapters) {
    ch.blocks = ch.blocks.flatMap((b) => (b.text.startsWith('Тихо падает') ? b.text.split('\n').map((l) => ({ k: 'verse' as const, text: l.trim() })) : [b]))
  }
  book.id = 'demo'
  book.title = 'Добро пожаловать в Храм Книги'
  book.author = 'Храм Книги'
  return book
}
